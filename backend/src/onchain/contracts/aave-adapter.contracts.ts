export class AaveAdapterContract {
  private contract: any;

  constructor(address: `0x${string}`, publicClient: PublicClient, walletClient?: WalletClient) {
    this.contract = getContract({
      address,
      abi: aaveAdapterAbi,
      client: { public: publicClient, wallet: walletClient }
    });
  }

  async totalAssets(): Promise<bigint> {
    return await this.contract.read.totalAssets();
  }

  async isActive(): Promise<boolean> {
    return await this.contract.read.isActive();
  }

  async deposit(amount: bigint) {
    if (!this.contract.write) throw new Error('WalletClient required for write');
    return await this.contract.write.deposit([amount]);
  }

  async withdraw(amount: bigint) {
    if (!this.contract.write) throw new Error('WalletClient required for write');
    return await this.contract.write.withdraw([amount]);
  }

  async harvest() {
    if (!this.contract.write) throw new Error('WalletClient required for write');
    return await this.contract.write.harvest();
  }
}
